// Dev-only: assemble tools/vecmat.wat into engine/simd-bytes.js (base64). Needs `npm i wabt` locally.
import fs from 'fs';
import wabtInit from 'wabt';
const wabt = await wabtInit();
const here = new URL('.', import.meta.url).pathname;
const mod = wabt.parseWat('vecmat.wat', fs.readFileSync(here + 'vecmat.wat', 'utf8'), { simd: true });
const { buffer } = mod.toBinary({});
fs.writeFileSync(here + '../engine/simd-bytes.js', `// generated by tools/build_wasm.mjs from tools/vecmat.wat — do not edit\nexport const VECMAT_WASM = '${Buffer.from(buffer).toString('base64')}';\n`);
console.log('wasm bytes', buffer.length);
